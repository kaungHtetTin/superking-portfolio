    data = {'name': 'QA rewards <sample> ' + 'promotion ' * 14, 'starts_on': str(today), 'ends_on': str(today + datetime.timedelta(days=2)), 'total_codes': 40,
            'instructions': 'Show your original label at the dealer.', 'prize_name[]': ['5,000 MMK cashback', 'Book', 'Smartwatch'], 'prize_quantity[]': [2, 3, 1]}
    invalid = post('/admin/lucky-draw', dict(data, total_codes=2), '/admin/lucky-draw/create')
    assert 'Winning prizes cannot exceed' in invalid.text
    assert 'QA rewards &lt;sample&gt;' in invalid.text
    created = post('/admin/lucky-draw', data, '/admin/lucky-draw/create')
