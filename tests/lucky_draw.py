    assert initial.headers['Referrer-Policy'] == 'no-referrer'
    assert 'not accepting plays' in post(winpath + '/reveal', source='/lucky-draw', session=customer).text
    assert query('SELECT COUNT(*) total FROM lucky_codes WHERE revealed_at IS NOT NULL')[0]['total'] == 0
    post(root + '/status', {'status': 'active'}, root)
    assert 'Reveal prize' in get(winpath, customer).text
    assert customer.post(BASE + winpath + '/reveal').status_code == 403
    assert 'Allow location access' in post(winpath+'/reveal', {}, '/lucky-draw', customer).text
    for invalid_location in [
        {'latitude':'91','longitude':'96','accuracy_m':'15'},
        {'latitude':'16','longitude':'181','accuracy_m':'15'},
        {'latitude':'16','longitude':'96','accuracy_m':'-1'},
        {'latitude':'NaN','longitude':'96','accuracy_m':'15'},
        {'latitude[]':['16'],'longitude':'96','accuracy_m':'15'},
    ]:
        invalid_location['location_consent'] = 'reveal-location-v1'
        assert 'valid device location' in post(winpath+'/reveal', invalid_location, '/lucky-draw', customer).text
    assert query('SELECT COUNT(*) total FROM lucky_locations')[0]['total'] == 0
    assert query('SELECT COUNT(*) total FROM lucky_codes WHERE revealed_at IS NOT NULL')[0]['total'] == 0
    result = post(winpath + '/reveal', source=winpath, session=customer)
    assert 'Congratulations! You won' in result.text and 'Show your original label' in result.text
    original = query("SELECT revealed_at FROM lucky_codes WHERE id=" + str(winner['id']))[0]['revealed_at']
