    assert query("SELECT revealed_at FROM lucky_codes WHERE id=" + str(winner['id']))[0]['revealed_at'] == original
    assert 'Congratulations! You won' in get(winpath, other).text
    assert 'Better luck next time' in post(losepath + '/reveal', source=losepath, session=customer).text
    assert query('SELECT COUNT(*) total FROM lucky_locations')[0]['total'] == 2
    distribution = get('/admin/distribution')
    assert '2</strong> recorded locations' in distribution.text
    assert winner['code'] not in distribution.text  # No bearer codes in reports.
    assert '1 distinct' not in distribution.text  # Map groups points client-side.
    assert 'no-store' in distribution.headers['Cache-Control']
    assert '2</strong> recorded locations' in get('/admin/distribution?campaign='+root.rsplit('/',1)[1]).text
    assert '0</strong> recorded locations' in get('/admin/distribution?from=2099-01-01').text
    assert 'Choose a valid from date' in get('/admin/distribution?from=invalid').text
    assert 'last date must' in get('/admin/distribution?from=2026-12-31&to=2026-01-01').text
    csv_locations = list(csv.reader(io.StringIO(get('/admin/distribution/export').text)))
    assert len(csv_locations) == 3 and csv_locations[0][2] == 'Latitude'
    assert csv_locations[1][1] == winner['code'][-6:] or csv_locations[1][1] == loser['code'][-6:]
    assert 'recorded reveal locations' in get('/admin').text
    assert 'not found' in get('/lucky-draw/' + '0'*24, customer, 404).text.lower()
    grouped = '-'.join(winner['code'][i:i+6] for i in range(0,24,6)).lower()
    assert 'Congratulations! You won' in post('/lucky-draw/lookup', {'code': grouped}, '/lucky-draw', customer).text
    assert 'lang=my' in post('/lucky-draw/lookup?lang=my', {'code': grouped}, '/lucky-draw?lang=my', customer).url
    assert 'complete 24-character' in post('/lucky-draw/lookup', {'code': 'invalid'}, '/lucky-draw', customer).text

    paused_code = next(x for x in codes if x['id'] not in (winner['id'], loser['id']))
    pausedpath = '/lucky-draw/' + paused_code['code']
    post(root + '/status', {'status': 'paused'}, root)
    assert 'not accepting plays' in post(pausedpath + '/reveal', source='/lucky-draw', session=customer).text
    assert 'Congratulations! You won' in get(winpath, customer).text
    # Redemption is allowed after a promotion closes; only new plays are blocked.
    post(root + '/status', {'status': 'closed'}, root)
    redeem = '/admin/lucky-draw/redeem?code=' + winner['code']
    assert 'Confirm prize given' in get(redeem).text
    assert customer.post(BASE + '/admin/lucky-draw/collect/' + winner['code'], allow_redirects=False).status_code == 302
    assert admin.post(BASE + '/admin/lucky-draw/collect/' + winner['code']).status_code == 403
    assert 'Prize marked as collected' in post('/admin/lucky-draw/collect/' + winner['code'], source=redeem).text
    assert 'No change:' in post('/admin/lucky-draw/collect/' + winner['code'], source='/admin/lucky-draw/redeem').text
    assert 'Already collected' in get(winpath, customer).text
    assert 'No change:' in post('/admin/lucky-draw/collect/' + loser['code'], source='/admin/lucky-draw/redeem').text
    assert 'No change:' in post('/admin/lucky-draw/collect/' + paused_code['code'], source='/admin/lucky-draw/redeem').text
    assert query("SELECT COUNT(*) total FROM admin_activity WHERE action='prize collected'")[0]['total'] == 1
    assert query('SELECT COUNT(*) total FROM lucky_codes WHERE redeemed_at IS NOT NULL')[0]['total'] == 1

    # Date gates remain in force even if an expired campaign is active.
