    assert abs((datetime.datetime.now(datetime.timezone.utc) - datetime.datetime.fromisoformat(location['recorded_at']).replace(tzinfo=datetime.timezone.utc)).total_seconds()) < 30
    # Reopening and repeated POSTs cannot overwrite or add first-reveal coordinates.
    post(winpath + '/reveal', {'latitude':'22','longitude':'98','accuracy_m':'50','location_consent':'reveal-location-v1'}, source='/lucky-draw', session=other)
