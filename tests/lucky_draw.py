    assert '&lt;sample&gt;' in created.text
    assert admin.post(BASE + root + '/generate').status_code == 403
    post(root + '/generate', source=root)
    codes = query('SELECT * FROM lucky_codes ORDER BY id')
    assert len(codes) == 40 and len({x['code'] for x in codes}) == 40
    assert len([x for x in codes if x['prize_id'] is not None]) == 6
    counts = query('SELECT p.name,COUNT(x.id) total FROM lucky_prizes p JOIN lucky_codes x ON x.prize_id=p.id GROUP BY p.id')
    assert {x['name']: x['total'] for x in counts} == {'5,000 MMK cashback': 2, 'Book': 3, 'Smartwatch': 1}
    duplicate = post(root + '/generate', source=root)
    assert 'already been generated' in duplicate.text
    assert len(query('SELECT id FROM lucky_codes')) == 40

    exported = get(root + '/export')
    rows = list(csv.reader(io.StringIO(exported.text)))
    assert len(rows) == 41 and rows[0] == ['Code', 'QR URL']
    assert 'prize' not in exported.text.lower() and 'no-store' in exported.headers['Cache-Control']
    assert rows[1][1] == BASE + '/lucky-draw/' + codes[0]['code']
    winner = next(x for x in codes if x['prize_id'] is not None)
    loser = next(x for x in codes if x['prize_id'] is None)
    winpath, losepath = '/lucky-draw/' + winner['code'], '/lucky-draw/' + loser['code']
    initial = get(winpath, customer)
